#!/usr/bin/env python3
"""Generate font.h (ASCII 0x20-0x7e, 8x16) from a PSF1 console font."""
import gzip, sys
d = gzip.open(sys.argv[1]).read()
import struct
if d[:2] == b'\x36\x04':
    off, h = 4, d[3]
else:
    assert d[:4] == b'\x72\xb5\x4a\x86', 'PSF1/PSF2 expected'
    off = struct.unpack_from('<I', d, 8)[0]
    h, w = struct.unpack_from('<2I', d, 24)
    assert w == 8
assert h == 16
out = ['/* generated by gen_font.py from %s */' % sys.argv[1].split('/')[-1],
       'static const unsigned char font8x16[95][16] = {']
for c in range(0x20, 0x7f):
    g = d[off + c*h: off + c*h + h]
    out.append('\t{' + ','.join('0x%02x' % b for b in g) + '},')
out.append('};')
open('font.h', 'w').write('\n'.join(out) + '\n')
