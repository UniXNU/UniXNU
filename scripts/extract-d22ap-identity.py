#!/usr/bin/env python3
"""Extract the iPhone X (D22AP) identity from a real Apple device tree.

The userland of this port is the iPhone X restore image, so MobileGestalt has
to read the product identity of that device.  The values are taken from the
device tree that the iPhone X firmware ships (the DeviceTree.d22ap.im4p of the
restore image), never invented.

Usage:
    extract-d22ap-identity.py D22AP.adt [-o scripts/d22ap_identity.py]

The generated module holds the root identity strings and the /product,
/buttons, /defaults and /options properties of the real tree.  Properties
that iBoot fills from the syscfg partition at boot are kept as they are in the
restore image: they carry the syscfg path, not a value.
"""
from pathlib import Path
import argparse
import struct
import sys


class Node:
    def __init__(self):
        self.props = []
        self.children = []

    @property
    def name(self):
        for key, _, value in self.props:
            if key == 'name':
                return value.split(b'\0')[0].decode()
        return '?'


def parse(buffer, offset=0):
    """Parse one Apple device tree node; returns (node, next offset)."""
    node = Node()
    props, children = struct.unpack_from('<II', buffer, offset)
    offset += 8
    for _ in range(props):
        name = buffer[offset:offset + 32].split(b'\0')[0].decode()
        size, = struct.unpack_from('<I', buffer, offset + 32)
        flags, length = size >> 31, size & 0x7fffffff
        node.props.append((name, flags, buffer[offset + 36:offset + 36 + length]))
        offset += 36 + ((length + 3) & ~3)
    for _ in range(children):
        child, offset = parse(buffer, offset)
        node.children.append(child)
    return node, offset


def find(root, name):
    for child in root.children:
        if child.name == name:
            return child
    return None


def collect(node, keep_placeholders=False):
    """The properties of a node, without the node bookkeeping."""
    result = {}
    for key, flags, value in node.props:
        if key in ('name', 'AAPL,phandle'):
            continue
        if flags and not keep_placeholders:
            continue
        result[key] = value
    return result


def literal(value):
    return repr(value)


def render(name, mapping, note):
    lines = [f'{name} = {{']
    for key in sorted(mapping):
        lines.append(f'    {key!r}: {literal(mapping[key])},')
    lines.append('}')
    return '\n'.join(lines) + f'  # {note}'


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('adt', type=Path, help='raw D22AP Apple device tree')
    parser.add_argument('-o', '--output', type=Path, default=None,
                        help='write the module here instead of stdout')
    args = parser.parse_args()

    root, _ = parse(args.adt.read_bytes())
    product = find(root, 'product')
    buttons = find(root, 'buttons')
    defaults = find(root, 'defaults')
    options = find(root, 'options')
    if product is None or buttons is None:
        raise SystemExit(f'{args.adt}: no /product or /buttons node')

    root_props = {key: value for key, _, value in root.props if key != 'AAPL,phandle'}
    compatible = root_props['compatible'].split(b'\0')
    identity = {
        'model': root_props['model'],
        'target-type': root_props['target-type'],
        'target-sub-type': root_props['target-sub-type'],
        'manufacturer': root_props['manufacturer'],
        'compatible': compatible[0] + b'\0' + compatible[1] + b'\0' + compatible[2] + b'\0',
    }

    text = ['"""Identity of the iPhone X (D22AP) target, extracted from its own device tree.',
            '',
            'Generated by scripts/extract-d22ap-identity.py; do not edit by hand.  The values come',
            'from the DeviceTree.d22ap.im4p of the iPhone X restore image: the root identity',
            'strings and the /product, /buttons, /defaults and /options properties.',
            '"""',
            '',
            render('IDENTITY', identity, 'root identity of the target device'),
            '',
            render('PRODUCT', collect(product), '/product of the target device'),
            '',
            render('BUTTONS', collect(buttons), '/buttons of the target device'),
            '',
            render('DEFAULTS', collect(defaults), '/defaults of the target device'),
            '',
            render('OPTIONS', collect(options), '/options of the target device'),
            '']

    if args.output:
        args.output.write_text('\n'.join(text))
        print(f'{args.output}: {len(text)} lines')
    else:
        sys.stdout.write('\n'.join(text))


if __name__ == '__main__':
    main()
